"""Liqwid V2 mainnet deployment.

Liqwid publishes the script hash of every component of every market and validator
generation in its public registry (``REGISTRY_URL``). ``registry_v6.json``, shipped
with this package, is a trimmed snapshot of it:

- ``scriptInfos``: the mainnet entries (tags ``liqwidMainnet``,
  ``liqwidMainnetLegacy`` and ``oracleMainnet``) of the component families listed in
  ``MARKET_FAMILIES`` and ``ORACLE_FAMILIES``, reduced to ``tag``, ``market``,
  ``componentName``, ``name``, ``type`` and ``scriptHash``;
- ``other.liqwidMainnetParams``: each market's ``marketDecimal`` and
  ``underlyingClass``;
- ``handKept``: what the registry does not list, namely the credential of the
  address that holds every MarketParams and CollateralParams record, and the four
  launch MarketState validators (Ada, DJED, SHEN, IUSD) used until 2023-07-19.

Keys starting with ``_`` carry provenance only. The snapshot is regenerated by
``tests/lending/liqwid/fixtures/_refresh_registry.py`` (development only, needs the
network). Nothing is read at import: :func:`default_deployment` loads the snapshot
on first use and caches it.
"""

from __future__ import annotations

import functools
import json
from collections.abc import Mapping
from dataclasses import dataclass
from dataclasses import field
from importlib.resources import files
from typing import Any
from typing import Final

REGISTRY_URL: Final[str] = "https://public.liqwid.finance/v6/registry.json"
REGISTRY_RESOURCE: Final[str] = "registry_v6.json"

# First MarketParams / MarketState / CollateralParams output (2023-02-02).
FIRST_SLOT: Final[int] = 83_736_022
# First token-bearing oracle feed output (2023-02-02 00:44 UTC).
FIRST_ORACLE_SLOT: Final[int] = 83_732_351
# Every oracle feed carries one token of this policy with an empty asset name.
ORACLE_TOKEN_POLICY: Final[
    str
] = "0fde77a0ea0833502b386d34e33d78f86c754bad309ee8bf008d7a9d"
# Mainnet POSIX seconds of a slot: slot + POSIX_SLOT_OFFSET.
POSIX_SLOT_OFFSET: Final[int] = 1_591_566_291

LEGACY_GENERATION: Final[str] = "legacy"
NEW_GENERATION: Final[str] = "new"

MARKET_TAGS: Final[frozenset[str]] = frozenset(
    {"liqwidMainnet", "liqwidMainnetLegacy"},
)
ORACLE_TAG: Final[str] = "oracleMainnet"

# Registry (componentName, type) -> the MarketComponents field it fills. A
# ("Loan", "Validator") entry is a new-generation loan validator when its name ends
# with NEW_LOAN_SUFFIX and a legacy one otherwise.
MARKET_FAMILIES: Final[Mapping[tuple[str, str], str]] = {
    ("MarketState", "MintingPolicy"): "market_state_policy",
    ("MarketParams", "MintingPolicy"): "market_params_policy",
    ("CollateralParams", "MintingPolicy"): "collateral_params_policy",
    ("QToken", "MintingPolicy"): "qtoken_policy",
    ("Borrow", "MintingPolicy"): "borrow_policy",
    ("NewBorrow", "MintingPolicy"): "new_borrow_policy",
    ("Liquidation", "MintingPolicy"): "liquidation_policy",
    ("MarketState", "Validator"): "market_state_validators",
    ("AnastasiaAuditMarketState", "Validator"): "market_state_validators",
    ("Loan", "Validator"): "loan_validators",
    ("NewLoanBorrowStaking", "StakeValidator"): "borrow_staking",
    ("AnastasiaAuditLoanBorrowStaking", "StakeValidator"): "borrow_staking",
    ("NewLoanLiquidationStaking", "StakeValidator"): "liquidation_staking",
    ("AnastasiaAuditLoanLiquidationStaking", "StakeValidator"): "liquidation_staking",
    ("Action", "Validator"): "actions",
    ("AnastasiaAuditAction", "Validator"): "actions",
    ("Batch", "Validator"): "batches",
    ("AnastasiaAuditBatch", "Validator"): "batches",
    ("BatchFinal", "Validator"): "batch_finals",
    ("AnastasiaAuditBatchFinal", "Validator"): "batch_finals",
}
NEW_LOAN_SUFFIX: Final[str] = "NewLoanValidator"

# Registry (componentName, type) -> oracle validator role, in role order.
ORACLE_FAMILIES: Final[Mapping[tuple[str, str], str]] = {
    ("Oracle", "Validator"): "v1",
    ("OracleWithHardCaps", "Validator"): "hard_caps",
    ("HardcodedOracleValidator", "Validator"): "pegs",
}
ORACLE_TOKEN_FAMILY: Final[tuple[str, str]] = ("Oracle", "MintingPolicy")

_SINGLE_FIELDS: Final[tuple[str, ...]] = (
    "market_state_policy",
    "market_params_policy",
    "collateral_params_policy",
    "qtoken_policy",
    "borrow_policy",
    "new_borrow_policy",
    "liquidation_policy",
)
_REQUIRED_FIELDS: Final[tuple[str, ...]] = _SINGLE_FIELDS[:4]
_TUPLE_FIELDS: Final[tuple[str, ...]] = (
    "market_state_validators",
    "legacy_loan_validators",
    "new_loan_validators",
    "borrow_staking",
    "liquidation_staking",
    "actions",
    "batches",
    "batch_finals",
)


@dataclass(frozen=True)
class MarketComponents:
    """Every script of one Liqwid V2 market, across validator generations.

    Hashes are 56-hex blake2b-224 digests. Tuples hold every generation the
    snapshot lists, in snapshot order; ``market_state_validators`` starts with the
    market's launch validator when it had one.
    """

    name: str
    underlying: str
    decimals: int
    market_state_policy: str
    market_params_policy: str
    collateral_params_policy: str
    qtoken_policy: str
    market_state_validators: tuple[str, ...]
    legacy_loan_validators: tuple[str, ...]
    new_loan_validators: tuple[str, ...]
    borrow_policy: str | None
    new_borrow_policy: str | None
    liquidation_policy: str | None
    borrow_staking: tuple[str, ...]
    liquidation_staking: tuple[str, ...]
    actions: tuple[str, ...]
    batches: tuple[str, ...]
    batch_finals: tuple[str, ...]

    @property
    def market_id(self) -> str:
        """The market identifier: its MarketState NFT policy.

        The NFT policy is the one identifier that survives every MarketState
        validator generation.
        """
        return self.market_state_policy

    @property
    def loan_validators(self) -> tuple[str, ...]:
        """Every loan validator, legacy generation first."""
        return self.legacy_loan_validators + self.new_loan_validators

    @property
    def loan_token_policies(self) -> frozenset[str]:
        """The loan-token policies: legacy ``Borrow`` and current ``NewBorrow``."""
        return frozenset(
            policy
            for policy in (self.borrow_policy, self.new_borrow_policy)
            if policy is not None
        )


@dataclass(frozen=True)
class OracleValidator:
    """One oracle feed validator: role ``v1``, ``hard_caps`` or ``pegs``."""

    role: str
    script_hash: str


@dataclass(frozen=True)
class _Index:
    by_id: dict[str, MarketComponents]
    loan: dict[str, tuple[MarketComponents, str]]
    state: dict[str, MarketComponents]
    params: dict[str, MarketComponents]
    collateral_params: dict[str, MarketComponents]
    qtoken: dict[str, MarketComponents]


def _put(index: dict[str, Any], key: str, value: object, what: str) -> None:
    if key in index and index[key] != value:
        msg = f"{what} {key} belongs to two Liqwid markets"
        raise ValueError(msg)
    index[key] = value


def _build_index(markets: tuple[MarketComponents, ...]) -> _Index:
    index = _Index({}, {}, {}, {}, {}, {})
    for market in markets:
        _put(index.by_id, market.market_id, market, "market id")
        _put(index.state, market.market_state_policy, market, "MarketState NFT")
        _put(index.params, market.market_params_policy, market, "MarketParams NFT")
        _put(
            index.collateral_params,
            market.collateral_params_policy,
            market,
            "CollateralParams NFT",
        )
        _put(index.qtoken, market.qtoken_policy, market, "qToken policy")
        for credential in market.legacy_loan_validators:
            _put(index.loan, credential, (market, LEGACY_GENERATION), "loan")
        for credential in market.new_loan_validators:
            _put(index.loan, credential, (market, NEW_GENERATION), "loan")
    return index


@dataclass(frozen=True)
class LiqwidDeployment:
    """The Liqwid V2 mainnet deployment: every market and the shared scripts.

    Raises:
        ValueError: when two markets claim the same market id, NFT policy, qToken
            policy or loan validator.
    """

    markets: tuple[MarketComponents, ...]
    param_credential: str
    oracle_validators: tuple[OracleValidator, ...]
    oracle_token_policy: str
    _index: _Index = field(init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        """Index the markets by every identifier the reader looks them up by."""
        object.__setattr__(self, "_index", _build_index(self.markets))

    def market(self, market_id: str) -> MarketComponents:
        """The market whose MarketState NFT policy is ``market_id``.

        Raises:
            KeyError: when no market has that id.
        """
        return self._index.by_id[market_id]

    def market_of_loan_validator(
        self,
        credential: str,
    ) -> tuple[MarketComponents, str] | None:
        """The market and generation (``legacy`` / ``new``) of a loan validator."""
        return self._index.loan.get(credential)

    def market_of_state_policy(self, policy: str) -> MarketComponents | None:
        """The market whose MarketState NFT policy is ``policy``."""
        return self._index.state.get(policy)

    def market_of_params_policy(self, policy: str) -> MarketComponents | None:
        """The market whose MarketParams NFT policy is ``policy``."""
        return self._index.params.get(policy)

    def market_of_collateral_params_policy(
        self,
        policy: str,
    ) -> MarketComponents | None:
        """The market whose CollateralParams NFT policy is ``policy``."""
        return self._index.collateral_params.get(policy)

    def market_of_qtoken(self, policy: str) -> MarketComponents | None:
        """The market whose qToken policy is ``policy``."""
        return self._index.qtoken.get(policy)

    @property
    def loan_token_policies(self) -> frozenset[str]:
        """Every loan-token policy of every market."""
        return frozenset().union(
            *(market.loan_token_policies for market in self.markets),
        )


def _underlying_unit(underlying_class: Mapping[str, Any]) -> str:
    policy = underlying_class["symbol"]["unCurrencySymbol"]
    name = underlying_class["name"]["unTokenName"]
    return policy + name if policy else "lovelace"


def _distinct(hashes: list[str]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(hashes))


def _market_components(
    name: str,
    params: Mapping[str, Any],
    entries: list[Mapping[str, Any]],
    launch_validator: str | None,
) -> MarketComponents:
    singles: dict[str, str] = {}
    lists: dict[str, list[str]] = {key: [] for key in _TUPLE_FIELDS}
    if launch_validator is not None:
        lists["market_state_validators"].append(launch_validator)
    for entry in entries:
        role = MARKET_FAMILIES[(entry["componentName"], entry["type"])]
        script_hash = entry["scriptHash"]
        if role == "loan_validators":
            new = entry["name"].endswith(NEW_LOAN_SUFFIX)
            role = "new_loan_validators" if new else "legacy_loan_validators"
        if role in _TUPLE_FIELDS:
            lists[role].append(script_hash)
        elif singles.setdefault(role, script_hash) != script_hash:
            msg = f"Liqwid market {name} lists two {role} hashes"
            raise ValueError(msg)
    missing = [key for key in _REQUIRED_FIELDS if key not in singles]
    if missing:
        msg = f"Liqwid market {name} has no {', '.join(missing)}"
        raise ValueError(msg)
    return MarketComponents(
        name=name,
        underlying=_underlying_unit(params["underlyingClass"]),
        decimals=int(params["marketDecimal"]),
        market_state_policy=singles["market_state_policy"],
        market_params_policy=singles["market_params_policy"],
        collateral_params_policy=singles["collateral_params_policy"],
        qtoken_policy=singles["qtoken_policy"],
        borrow_policy=singles.get("borrow_policy"),
        new_borrow_policy=singles.get("new_borrow_policy"),
        liquidation_policy=singles.get("liquidation_policy"),
        market_state_validators=_distinct(lists["market_state_validators"]),
        legacy_loan_validators=_distinct(lists["legacy_loan_validators"]),
        new_loan_validators=_distinct(lists["new_loan_validators"]),
        borrow_staking=_distinct(lists["borrow_staking"]),
        liquidation_staking=_distinct(lists["liquidation_staking"]),
        actions=_distinct(lists["actions"]),
        batches=_distinct(lists["batches"]),
        batch_finals=_distinct(lists["batch_finals"]),
    )


def _oracles(
    entries: list[Mapping[str, Any]],
) -> tuple[tuple[OracleValidator, ...], str]:
    found: dict[str, str] = {}
    token_policy = None
    for entry in entries:
        family = (entry["componentName"], entry["type"])
        if family == ORACLE_TOKEN_FAMILY:
            token_policy = entry["scriptHash"]
        elif family in ORACLE_FAMILIES:
            found.setdefault(ORACLE_FAMILIES[family], entry["scriptHash"])
    roles = list(ORACLE_FAMILIES.values())
    if token_policy is None or any(role not in found for role in roles):
        msg = "Liqwid registry lacks an oracle validator or the oracle token"
        raise ValueError(msg)
    return tuple(OracleValidator(role, found[role]) for role in roles), token_policy


@functools.lru_cache(maxsize=1)
def _bundled_registry() -> Mapping[str, Any]:
    resource = files(__package__) / REGISTRY_RESOURCE
    return json.loads(resource.read_text())


def load_deployment(data: Mapping[str, Any]) -> LiqwidDeployment:
    """Assemble a deployment from a registry document.

    ``data`` is the bundled snapshot or a registry fetched from ``REGISTRY_URL``.
    Markets are the keys of ``other.liqwidMainnetParams``, sorted by name; script
    entries of other tags, families or markets are ignored. A document without a
    ``handKept`` block (a fetched registry) takes the bundled snapshot's.

    Args:
        data: the registry document.

    Returns:
        The deployment.

    Raises:
        ValueError: when a market lacks a required NFT or qToken policy or lists
            two hashes for a single-hash family, an oracle role or the oracle token
            is missing, or a launch validator names an unknown market.
        KeyError: when the document lacks ``scriptInfos`` or
            ``other.liqwidMainnetParams``.
    """
    params = data["other"]["liqwidMainnetParams"]
    hand_kept = data.get("handKept") or _bundled_registry()["handKept"]
    launch = hand_kept["launchMarketStateValidators"]
    unknown = sorted(set(launch) - set(params))
    if unknown:
        msg = f"launch MarketState validators for unknown markets {unknown}"
        raise ValueError(msg)
    per_market: dict[str, list[Mapping[str, Any]]] = {name: [] for name in params}
    oracle_entries: list[Mapping[str, Any]] = []
    for entry in data["scriptInfos"]:
        family = (entry.get("componentName"), entry.get("type"))
        if entry.get("tag") == ORACLE_TAG:
            oracle_entries.append(entry)
        elif (
            entry.get("tag") in MARKET_TAGS
            and entry.get("market") in per_market
            and family in MARKET_FAMILIES
        ):
            per_market[entry["market"]].append(entry)
    oracle_validators, oracle_token_policy = _oracles(oracle_entries)
    markets = tuple(
        _market_components(name, params[name], per_market[name], launch.get(name))
        for name in sorted(params)
    )
    return LiqwidDeployment(
        markets=markets,
        param_credential=hand_kept["paramCredential"],
        oracle_validators=oracle_validators,
        oracle_token_policy=oracle_token_policy,
    )


@functools.lru_cache(maxsize=1)
def default_deployment() -> LiqwidDeployment:
    """The deployment of the bundled ``registry_v6.json`` snapshot (cached)."""
    return load_deployment(_bundled_registry())
