@dataclass(frozen=True)
class DriftFinding:
    """One way the chain or the published registry departs from the deployment.

    ``kind`` is ``"registry"`` (the published registry and the bundled snapshot
    differ), ``"params"`` (a MarketParams record has an unknown layout or names a
    script the snapshot does not bundle for its market) or ``"identity"`` (an
    identity token sits at a credential the snapshot does not list for it).
    ``market`` is the market's registry name, None for a deployment-wide component.
    ``component`` is the ``MarketComponents`` / ``LiqwidDeployment`` field the hash
    belongs to (``"staking"`` for a p[34] withdraw-zero hash, whose pair order
    varies by market; ``"layout"`` / ``"datum"`` for an unreadable MarketParams;
    ``"market"`` for a whole market; the registry's own name for a component the
    snapshot does not track). ``script_hash`` is the hash that drifted: a script
    hash or policy, the observed credential for an identity finding, the
    MarketParams policy for a layout finding.

    Raises:
        ValueError: when ``kind`` is not one of ``DRIFT_KINDS``.
    """

    kind: str
    market: str | None
    component: str
    script_hash: str
    detail: str

    def __post_init__(self) -> None:
        """Reject an unknown finding kind."""
        if self.kind not in DRIFT_KINDS:
            msg = f"unknown drift kind {self.kind!r}"
            raise ValueError(msg)


def check_deployment(
    params: Iterable[PoolStateInfo] = (),
    *,
    registry: Mapping[str, Any] | None = None,
    observed_credentials: Iterable[tuple[str, str]] = (),
    deployment: LiqwidDeployment | None = None,
) -> list[DriftFinding]:
    """Every way the given chain and registry data depart from the deployment.

    Pure: the caller fetches. ``params`` are live (unspent) MarketParams UTxOs;
    each market is found from the MarketParams NFT policy it holds, and a UTxO
    holding none is not a MarketParams record and is skipped, as is a parked
    ``Constr0 []`` output. ``registry`` is a freshly fetched v6 registry document
    (``scriptInfos``). ``observed_credentials`` are ``(payment credential,
    identity policy)`` pairs seen on chain; policies that are not a MarketState
    NFT, loan token or oracle token are ignored, as is a pair at
    :data:`BURN_CREDENTIAL` (a retired token). ``deployment`` defaults to
    :func:`default_deployment`.

    Returns:
        The findings, de-duplicated and sorted by (kind, market, component,
        script_hash, detail); empty when nothing drifted.
    """
    active = deployment if deployment is not None else default_deployment()
    found: set[DriftFinding] = set()
    for info in params:
        found.update(_params_drift(info, active))
    if registry is not None:
        found.update(_registry_drift(registry, active))
    found.update(_identity_drift(observed_credentials, active))
    return sorted(found, key=_finding_order)


def _finding_order(finding: DriftFinding) -> tuple[str, str, str, str, str]:
    """Deterministic sort key of a finding."""
    return (
        finding.kind,
        finding.market or "",
        finding.component,
        finding.script_hash,
        finding.detail,
    )


# --- Parameter drift ---------------------------------------------------------


def _params_market(
    info: PoolStateInfo,
    deployment: LiqwidDeployment,
) -> MarketComponents | None:
    """The market whose MarketParams NFT ``info`` holds, if any."""
    for unit in info.assets.root:
        if unit == "lovelace":
            continue
        market = deployment.market_of_params_policy(policy_of(unit))
        if market is not None:
            return market
    return None


def _params_scripts(
    record: MarketParamsDatum,
    market: MarketComponents,
) -> list[tuple[str, str, str, tuple[str, ...]]]:
    """(parameter, component, hash, bundled hashes) for each script a record names."""
    named: list[tuple[str, str, str | None, tuple[str, ...]]] = [
        (
            "p[9] legacy loan validator",
            "loan_validators",
            record.legacy_loan_validator,
            market.loan_validators,
        ),
        ("p[20] action validator", "actions", record.action_validator, market.actions),
        ("p[21] batch validator", "batches", record.batch_validator, market.batches),
        (
            "p[35] loan validator",
            "loan_validators",
            record.loan_validator,
            market.loan_validators,
        ),
    ]
    staking = market.borrow_staking + market.liquidation_staking
    for script_hash in record.withdraw_zero or ():
        named.append(("p[34] withdraw-zero validator", "staking", script_hash, staking))
    return [
        (label, component, script_hash, bundled)
        for label, component, script_hash, bundled in named
        if script_hash is not None
    ]


def _params_drift(
    info: PoolStateInfo,
    deployment: LiqwidDeployment,
) -> list[DriftFinding]:
    """Findings for one MarketParams UTxO (none for a parked or foreign UTxO)."""
    market = _params_market(info, deployment)
    if market is None:
        return []
    where = f"MarketParams {out_ref(info)}"
    try:
        length = field_count(info.datum_cbor)
        if length is None:
            return []
        if length not in MARKET_PARAMS_LENGTHS:
            return [
                DriftFinding(
                    "params",
                    market.name,
                    "layout",
                    market.market_params_policy,
                    f"{where}: {length} fields, known layouts "
                    f"{sorted(MARKET_PARAMS_LENGTHS)}",
                ),
            ]
        record = decode_market_params(info.datum_cbor)
    except LIQWID_DECODE_ERRORS as exc:
        return [
            DriftFinding(
                "params",
                market.name,
                "datum",
                market.market_params_policy,
                f"{where}: undecodable datum ({exc})",
            ),
        ]
    return [
        DriftFinding(
            "params",
            market.name,
            component,
            script_hash,
            f"{where}: {label} is not bundled for the market",
        )
        for label, component, script_hash, bundled in _params_scripts(record, market)
        if script_hash not in bundled
    ]


# --- Registry drift ----------------------------------------------------------


def _registry_entries(registry: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    """The registry's ``scriptInfos`` entries that are mappings."""
    entries = registry.get("scriptInfos") or ()
    return [entry for entry in entries if isinstance(entry, Mapping)]


def _entry_key(entry: Mapping[str, Any]) -> tuple[str, str]:
    """(componentName, type) of a registry entry."""
    return (str(entry.get("componentName", "")), str(entry.get("type", "")))


def _published_markets(
    registry: Mapping[str, Any],
) -> tuple[dict[str, dict[str, set[str]]], list[DriftFinding]]:
    """Per published market, the hashes of each tracked field; untracked names."""
    markets: dict[str, dict[str, set[str]]] = {}
    untracked: list[DriftFinding] = []
    for entry in _registry_entries(registry):
        market = entry.get("market")
        if entry.get("tag") not in MARKET_TAGS or not market:
            continue
        key = _entry_key(entry)
        script_hash = str(entry.get("scriptHash", ""))
        fields = markets.setdefault(str(market), {})
        if key in MARKET_COMPONENT_ROLES:
            fields.setdefault(MARKET_COMPONENT_ROLES[key], set()).add(script_hash)
        elif key not in IGNORED_MARKET_COMPONENTS:
            untracked.append(
                DriftFinding(
                    "registry",
                    str(market),
                    key[0],
                    script_hash,
                    f"registry {key[1]} the bundled snapshot does not track",
                ),
            )
    return markets, untracked


def _bundled_fields(market: MarketComponents) -> dict[str, set[str]]:
    """The hashes the snapshot holds for each registry-filled field of a market."""
    fields: dict[str, set[str]] = {}
    for name in MARKET_ROLE_FIELDS:
        value = getattr(market, name)
        if name in _MULTI_ROLE_FIELDS:
            fields[name] = set(value)
        else:
            fields[name] = {value} if value else set()
    return fields


def _hash_drift(
    market: str | None,
    component: str,
    published: set[str],
    bundled: set[str],
) -> list[DriftFinding]:
    """Findings for the hashes one side lists and the other lacks."""
    added = [
        DriftFinding(
            "registry",
            market,
            component,
            script_hash,
            "published in the registry, absent from the bundled snapshot",
        )
        for script_hash in published - bundled
    ]
    dropped = [
        DriftFinding(
            "registry",
            market,
            component,
            script_hash,
            "bundled, absent from the published registry",
        )
        for script_hash in bundled - published - UNREGISTERED_MARKET_STATE_VALIDATORS
    ]
    return added + dropped


def _market_registry_drift(
    registry: Mapping[str, Any],
    deployment: LiqwidDeployment,
) -> list[DriftFinding]:
    """Market-level registry drift: whole markets and each component's hashes."""
    published, findings = _published_markets(registry)
    bundled = {market.name: market for market in deployment.markets}
    for name in published.keys() - bundled.keys():
        policy = min(published[name].get("market_state_policy") or {""})
        findings.append(
            DriftFinding(
                "registry",
                name,
                "market",
                policy,
                "market published in the registry, absent from the bundled snapshot",
            ),
        )
    for name in bundled.keys() - published.keys():
        findings.append(
            DriftFinding(
                "registry",
                name,
                "market",
                bundled[name].market_state_policy,
                "bundled market absent from the published registry",
            ),
        )
    for name in bundled.keys() & published.keys():
        listed = published[name]
        for component, hashes in _bundled_fields(bundled[name]).items():
            findings.extend(
                _hash_drift(name, component, listed.get(component, set()), hashes),
            )
    return findings


def _oracle_registry_drift(
    registry: Mapping[str, Any],
    deployment: LiqwidDeployment,
) -> list[DriftFinding]:
    """Deployment-wide registry drift: oracle validators and the oracle token."""
    findings: list[DriftFinding] = []
    published: dict[str, set[str]] = {}
    for entry in _registry_entries(registry):
        if entry.get("tag") != ORACLE_TAG:
            continue
        key = _entry_key(entry)
        script_hash = str(entry.get("scriptHash", ""))
        if key in ORACLE_COMPONENT_ROLES:
            published.setdefault(ORACLE_COMPONENT_ROLES[key], set()).add(script_hash)
        elif key not in IGNORED_ORACLE_COMPONENTS:
            findings.append(
                DriftFinding(
                    "registry",
                    None,
                    key[0],
                    script_hash,
                    f"registry {key[1]} the bundled snapshot does not track",
                ),
            )
    bundled: dict[str, set[str]] = {ORACLE_TOKEN_ROLE: {deployment.oracle_token_policy}}
    for validator in deployment.oracle_validators:
        bundled.setdefault(validator.role, set()).add(validator.script_hash)
    for role in published.keys() | bundled.keys():
        component = (
            ORACLE_TOKEN_ROLE if role == ORACLE_TOKEN_ROLE else "oracle_validators"
        )
        findings.extend(
            _hash_drift(
                None,
                component,
                published.get(role, set()),
                bundled.get(role, set()),
            ),
        )
    return findings


def _registry_drift(
    registry: Mapping[str, Any],
    deployment: LiqwidDeployment,
) -> list[DriftFinding]:
    """Every difference between a published registry and the bundled snapshot."""
    return _market_registry_drift(registry, deployment) + _oracle_registry_drift(
        registry,
        deployment,
    )


# --- Identity drift ----------------------------------------------------------


def _identity_homes(
    deployment: LiqwidDeployment,
) -> dict[str, tuple[str | None, str, frozenset[str]]]:
    """Identity policy -> (market, component, credentials the token may sit at)."""
    homes: dict[str, tuple[str | None, str, frozenset[str]]] = {
        deployment.oracle_token_policy: (
            None,
            "oracle_validators",
            frozenset(v.script_hash for v in deployment.oracle_validators),
        ),
    }
    for market in deployment.markets:
        homes[market.market_state_policy] = (
            market.name,
            "market_state_validators",
            frozenset(market.market_state_validators),
        )
        for policy in market.loan_token_policies:
            homes[policy] = (
                market.name,
                "loan_validators",
                frozenset(market.loan_validators),
            )
    return homes


def _identity_drift(
    observed: Iterable[tuple[str, str]],
    deployment: LiqwidDeployment,
) -> list[DriftFinding]:
    """Identity tokens observed at a credential the snapshot does not list.

    A token at :data:`BURN_CREDENTIAL` is retired and never a finding.
    """
    homes = _identity_homes(deployment)
    findings: list[DriftFinding] = []
    for credential, policy in observed:
        home = homes.get(policy)
        if home is None or credential == BURN_CREDENTIAL or credential in home[2]:
            continue
        findings.append(
            DriftFinding(
                "identity",
                home[0],
                home[1],
                credential,
                f"identity policy {policy} at an unlisted credential",
            ),
        )
    return findings
